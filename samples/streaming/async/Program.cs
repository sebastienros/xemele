using System.Text;
using Xemele;
using Xemele.Streaming;
using Reader = Xemele.Streaming.XmlReader;
using Writer = Xemele.XmlWriter;
using var input = new MemoryStream(Encoding.UTF8.GetBytes("<r>hello</r>"));
var document = await XmlDocument.LoadAsync(input);
using var output = new MemoryStream();
await document.SaveAsync(output, new() { OmitXmlDeclaration = true });
if (Encoding.UTF8.GetString(output.ToArray()) != "<r>hello</r>") throw new InvalidOperationException();
output.Position = 0;
await XmlSaxParser.ParseAsync(output, new XmlSaxCallbacks());
output.Position = 0;
await using var reader = Reader.Create(output);
int tokens = 0;
while (await reader.ReadAsync()) tokens++;
using var forwarded = new MemoryStream();
await using var writer = Writer.Create(forwarded, new() { OmitXmlDeclaration = true });
await writer.WriteStartElementAsync("r");
await writer.WriteTextAsync("hello".AsMemory());
await writer.WriteEndElementAsync();
await writer.WriteEndDocumentAsync();
if (!forwarded.ToArray().AsSpan().SequenceEqual(output.ToArray())) throw new InvalidOperationException();
Console.WriteLine($"DOM async load/save, SAX, reader ({tokens} tokens), and forward async writer agree: <r>hello</r>");
