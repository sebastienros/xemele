using Xemele;
using Xemele.Html;
using System.Runtime.InteropServices;
if (RuntimeInformation.FrameworkDescription != ".NET 10.0.11") throw new Exception("Actual pinned runtime required.");
var document = new HtmlDocument();
var html = document.CreateElement("HTML");
document.DocumentNode.AppendChild(html);
var template = document.CreateElement("template");
html.AppendChild(template);
template.TemplateContent!.AppendChild(document.CreateText("detached contents"));
var foreign = document.CreateElement("foreignObject", "http://www.w3.org/2000/svg");
html.AppendChild(foreign);
foreign.SetAttribute(new("href", "#target", "http://www.w3.org/1999/xlink", "xlink"));
var fragment = document.CreateFragment();
fragment.AppendChild(document.CreateText("HTML\0text"));
html.AppendChild(fragment);
var imported = new HtmlDocument().Import(template);
if (html.LocalName != "html" || html.GetTextContent() != "HTML\0text" || imported.TemplateContent!.GetTextContent() != "detached contents") throw new Exception("Model semantics");
var context = new HtmlFragmentContext(foreign, HtmlQuirksMode.LimitedQuirks);
var token = new HtmlToken(HtmlTokenKind.StartTag, "p", "", new[] { new HtmlAttribute("id", "x") }, false, null, new XmlLocation(null, 1, 1, null));
if (context.ContextElement != foreign || token.Attributes.Count != 1) throw new Exception();
var xml = new XmlDocument();
var root = xml.CreateElement("root");
xml.DocumentNode.AppendChild(root);
if (xml.RootElement.LocalName != "root") throw new Exception("Earlier XML tree");
Console.WriteLine("HTML owner/navigation/template/foreign/token/context and earlier XML probes passed; actual runtime " + RuntimeInformation.FrameworkDescription);
