using System.Runtime.InteropServices;
using Xemele;
using Xemele.Html;
if (RuntimeInformation.FrameworkDescription != ".NET 10.0.11") throw new Exception("Pinned runtime required");
var document = new HtmlDocument();
var pi = document.CreateProcessingInstruction("Case", "data\0?>");
document.DocumentNode.AppendChild(pi);
var html = document.CreateElement("HTML");
document.DocumentNode.AppendChild(html);
html.AppendChild(document.CreateText("text"));
var template = document.CreateElement("template");
html.AppendChild(template);
template.TemplateContent!.AppendChild(pi.Clone());
var imported = new HtmlDocument().Import(template);
if (imported.TemplateContent!.FirstChild!.LocalName != "Case" || document.DocumentNode.GetTextContent() != "text") throw new Exception("PI ownership/text semantics");
pi.Value = "changed";
if (pi.Kind != HtmlNodeKind.ProcessingInstruction || (int)HtmlTokenKind.ProcessingInstruction != 6) throw new Exception("PI kinds");
var xml = new XmlDocument();
var root = xml.CreateElement("root");
xml.DocumentNode.AppendChild(root);
if (xml.RootElement.LocalName != "root") throw new Exception("Earlier XML model");
Console.WriteLine("PI ownership/copy/template/text and prior HTML/XML model passed on " + RuntimeInformation.FrameworkDescription);
