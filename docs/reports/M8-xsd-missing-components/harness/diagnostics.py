"""Bounded failure summaries and input hashes; no runtime work or raw archive."""
import json
import re
import shutil
from pathlib import Path
import bindings as b

MAX_COMMANDS = 12
MAX_READ_BYTES = 65536
MAX_DIAGNOSTICS = 24
MAX_TEXT = 768
COMPILER = re.compile(r'\b(error|warning)\s+([A-Za-z]+\d+)\s*:\s*(.*)', re.IGNORECASE)
EXCEPTION = re.compile(r'^(?:Unhandled exception\.\s*)?([\w.]*(?:Error|Exception))\s*:\s*(.*)')


def capture_inputs(directory, index, argv, environment, restore_binding=None):
    """Before launch: exact command, reviewed source and selected toolchain identities.
    These describe observed declared inputs, not an exhaustive MSBuild read trace.
    """
    from family import nested
    identities = {}
    b.verify_executable(argv,environment)
    executable = shutil.which(argv[0], path=environment.get('PATH'))
    assert executable, 'Executable identity unavailable before launch'
    identities[b.key(executable)] = b.digest(executable)
    for arg in argv[1:]:
        if arg.endswith(('.py', '.dll', '.csproj')):
            path = b.resolve(arg)
            if path.is_file():identities[b.key(path)] = b.digest(path)
    if Path(executable).resolve() == b.DOTNET.resolve() and argv[1:2] in [['build'], ['restore']]:
        config = json.loads((b.ROOT / 'global.json').read_text())['sdk']
        assert config['rollForward'] == 'disable', 'Selected SDK identity requires exact version'
        sdk = b.DOTNET.parent / 'sdk' / config['version']
        for relative in ['MSBuild.dll', 'MSBuild.deps.json', 'MSBuild.runtimeconfig.json',
                         'Roslyn/bincore/csc.dll', 'Roslyn/bincore/csc.deps.json', 'Roslyn/bincore/csc.runtimeconfig.json',
                         'Sdks/Microsoft.NET.Sdk/Sdk/Sdk.props',
                         'Sdks/Microsoft.NET.Sdk/Sdk/UseArtifactsOutputPath.props',
                         'Sdks/Microsoft.NET.Sdk/targets/Microsoft.NET.DefaultArtifactsPath.props',
                         'Sdks/Microsoft.NET.Sdk/targets/Microsoft.NET.DefaultOutputPaths.targets',
                         'Sdks/Microsoft.NET.Sdk/targets/Microsoft.NET.Sdk.DefaultItems.props',
                         'Sdks/Microsoft.NET.Sdk/targets/Microsoft.NET.Sdk.DefaultItems.targets']:
            path = sdk / relative
            identities[b.key(path)] = b.digest(path)
        # Restore-derived declared inputs can explain configuration/assets failures.
        # No package/cache/generated bytes are copied or claimed as a full read set.
        for arg in argv:
            if arg.startswith('-p:ArtifactsPath='):
                active = Path(arg.split('=', 1)[1]).resolve()
                assert b.OUT.resolve() in active.parents
                for path in (active / 'obj').rglob('*'):
                    if path.is_file() and (path.name == 'project.assets.json' or path.name.endswith(('.nuget.g.props', '.nuget.g.targets'))):
                        identities[b.key(path)] = b.digest(path)
    source = json.loads(b.SOURCE.read_text())
    record = {'argv': list(argv), 'cwd':str(b.ROOT), 'environmentSha256':b.identity_sha(environment), 'capturePhase': 'before-launch',
              'reviewedSourceManifestSha256': b.digest(b.SOURCE),
              'reviewedSourceIdentitiesSha256': b.identity_sha(source['identities']),
              'precedingRestore':restore_binding,
              'observedInputIdentities': identities, 'observedInputIdentitiesSha256': b.identity_sha(identities),
              'scope': 'reviewed declared source plus observed executable/entry/selected SDK/restore-derived inputs; not exhaustive build reads'}
    path=Path(directory)/f'command-inputs-{index:03d}.json'
    nested.durable(path,record)
    return {'path':str(path),'sha256':b.digest(path)}


def log_summary(path, limit=MAX_DIAGNOSTICS):
    """At most 64KiB from a closed log; retain only structured diagnostic excerpts."""
    size = path.stat().st_size
    with path.open('rb') as stream:
        if size <= MAX_READ_BYTES:
            chunks = [(stream.read(MAX_READ_BYTES), False, False)]
        else:
            chunks = [(stream.read(MAX_READ_BYTES // 2), False, True)]
            stream.seek(size - MAX_READ_BYTES // 2)
            chunks.append((stream.read(MAX_READ_BYTES // 2), True, False))
    diagnostics = []; seen = set(); matched = 0
    for chunk, partial_start, partial_end in chunks:
        lines = chunk.decode('utf-8', errors='replace').splitlines()
        if partial_start: lines = lines[1:]  # never report a sliced line as complete
        if partial_end and not chunk.endswith(b'\n'):lines=lines[:-1]
        for line in lines:
            text = line.strip()
            # JSON payloads and arbitrary console output are not diagnostic summaries.
            if not text or text.startswith(('{', '[{', '"')): continue
            compiler = COMPILER.search(text)
            exception = EXCEPTION.match(text)
            if compiler:
                entry = {'kind': 'compiler', 'severity': compiler[1].lower(), 'code': compiler[2], 'text': text[:MAX_TEXT], 'textTruncated':len(text)>MAX_TEXT}
            elif exception:
                entry = {'kind': 'exception', 'type': exception[1][:96], 'text': exception[2][:MAX_TEXT], 'textTruncated':len(exception[2])>MAX_TEXT}
            elif text.startswith(('[FAIL]', 'Failed ')):
                entry = {'kind': 'test-failure', 'text': text[:MAX_TEXT]}
            else: continue
            identity = json.dumps(entry, sort_keys=True)
            if identity in seen: continue
            seen.add(identity); matched += 1
            if len(diagnostics) < limit: diagnostics.append(entry)
    return {'sizeBytes': size, 'bytesScanned': min(size, MAX_READ_BYTES), 'scanTruncated': size > MAX_READ_BYTES,
            'diagnosticsTruncated': matched > limit, 'diagnostics': diagnostics,
            'fallback': None if matched else 'No recognized diagnostic in bounded scan; cause remains unknown'}


def preserve_failure(runner, outer_error=None, outer_detail=None, abort=False, extra_directories=()):
    """Caller must prove whole-family absence before any raw output is consumed."""
    from family import nested
    assert runner.closed and runner.receipt and runner.receipt['ownership']['allOwnedGroupsAbsent']
    assert all(row['directChildReaped'] and row['ownedGroupAbsent'] and row['logClosed']
               and row['nestedOwnership']['allOwnedGroupsAbsent'] for row in runner.sequence)
    directory = runner.directory
    observations = []; failed_count = 0; remaining_diagnostics = MAX_DIAGNOSTICS
    roots={directory.resolve(),*(Path(p).resolve() for p in extra_directories)}
    assert all(b.OUT.resolve() in root.parents for root in roots)
    receipts=sorted({p for root in roots for p in root.rglob('lifecycle-*.json')})
    for receipt in receipts:
        row = json.loads(receipt.read_text())
        if row['reason'] == 'completed' and row['exit'] == 0 and not row.get('lateSuccess', False): continue
        failed_count += 1
        if len(observations) >= MAX_COMMANDS: continue
        index = int(receipt.stem.rsplit('-', 1)[1])
        log = receipt.parent / f'command-{index}.log'
        inputs = receipt.parent / f'command-inputs-{index:03d}.json'
        observation = {'argv': row['argv'], 'exit': row['exit'], 'reason': row['reason'],
                       'lifecycleReceipt': b.key(receipt), 'lifecycleSha256': b.digest(receipt)}
        if inputs.is_file():
            data = json.loads(inputs.read_text())
            actual_sha=b.digest(inputs)
            verified=data['argv']==row['argv'] and row.get('inputReceiptSha256')==actual_sha
            observation.update(inputReceipt=b.key(inputs),inputReceiptSha256=row.get('inputReceiptSha256'),
                               observedInputReceiptSha256=actual_sha,inputReceiptVerified=verified)
            if verified:
                observation.update(inputIdentitiesSha256=data['observedInputIdentitiesSha256'],
                                   sourceManifestSha256=data['reviewedSourceManifestSha256'])
            else:observation['inputFallback']='Input receipt lacks matching pre-launch lifecycle binding; identities untrusted'
        else: observation['inputReceipt'] = 'Unavailable; do not infer input identities'
        if log.is_file():
            observation['logSha256'] = b.digest(log)
            observation['diagnosticSummary'] = log_summary(log,remaining_diagnostics)
            remaining_diagnostics-=len(observation['diagnosticSummary']['diagnostics'])
        else: observation['diagnosticSummary'] = {'fallback': 'Raw log unavailable; cause remains unknown'}
        observations.append(observation)
    if not observations and outer_error is None: return None
    path = directory / ('failure-diagnostics-abort.json' if abort else 'failure-diagnostics.json')
    record = {'outcomeCompleted': runner.receipt['completed'] and outer_error is None,
              'outerError': outer_error, 'outerDetail': None if outer_detail is None else outer_detail[:MAX_TEXT],
              'failedCommandsObserved': failed_count, 'commandsTruncated': failed_count > MAX_COMMANDS,
              'observations': observations, 'maximumDiagnosticExcerpts':MAX_DIAGNOSTICS,'maximumTextCharacters':MAX_TEXT,
              'counterEnabledByDiagnostics': False,
              'scope': 'Actual bounded diagnostic excerpts after family absence; raw logs deleted separately; no success claim'}
    nested.durable(path, record)
    return {'path': str(path), 'sha256': b.digest(path)}
