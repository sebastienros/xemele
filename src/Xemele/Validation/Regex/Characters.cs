    internal static bool Block(ReadOnlySpan<char> name, ISchemaOperation operation, XmlLocation at, out int first, out int last)
    {
        foreach (var (Name, First, Last) in Blocks)
        {
            if (!operation.Charge(1, at))
            {
                throw SchemaSnapshots.Failure(operation);
            }

            if (name.SequenceEqual(Name))
            {
                first = First;
                last = Last;
                return true;
            }
        }
        first = last = 0;
        return false;
    }
